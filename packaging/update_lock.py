"""Regenerate packaging/requirements-build.txt, the hash-pinned build lock.

    python packaging/update_lock.py

Resolves TOP_LEVEL in a throwaway venv, then downloads the exact wheels
that resolved and records their SHA-256 hashes. The build installs with
`pip --require-hashes --only-binary=:all:`, so a build can only ever use
these exact files. Bump a version here, rerun, rebuild, and run the
compatibility checklist in docs/COMPATIBILITY.md before releasing.

Needs network access. Run it with the build Python (see
SUPPORTED_BUILD_PYTHONS in build.py):
    py -3.13 packaging/update_lock.py
Every pinned wheel is pure Python or abi3, so the lock also installs on the
other supported build Python (3.12). MARKERS covers backport packages that
older resolvers pulled in; none are needed on 3.12+.
"""

import hashlib
import subprocess
import sys
import tempfile
import venv
from pathlib import Path

TOP_LEVEL = [
    "PySide6-Essentials==6.8.3",
    "pyinstaller==6.22.3",
    # PyInstaller requires setuptools. Pinned explicitly: Python 3.12+ venvs
    # don't seed it, and 3.9's seeded copy is too old for newer Pythons.
    "setuptools==80.9.0",
]

# Dependencies that only exist for older Pythons.
MARKERS = {
    "importlib-metadata": 'python_version < "3.10"',
    "zipp": 'python_version < "3.10"',
}

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "packaging" / "requirements-build.txt"


def _norm(name):
    return name.lower().replace("_", "-").replace(".", "-")


def main():
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        venv.EnvBuilder(with_pip=True).create(tmp / "venv")
        py = str(tmp / "venv" / "Scripts" / "python.exe")
        subprocess.check_call([py, "-m", "pip", "install", "-q", "--only-binary=:all:", *TOP_LEVEL])
        frozen = subprocess.check_output([py, "-m", "pip", "freeze", "--all"], text=True).split()
        pins = [p for p in frozen if "==" in p and _norm(p.split("==")[0]) not in ("pip", "wheel")]

        wheels = tmp / "wheels"
        subprocess.check_call([py, "-m", "pip", "download", "-q", "--no-deps", "--only-binary=:all:",
                               "-d", str(wheels), *pins])
        hashes = {}
        for whl in wheels.iterdir():
            name = _norm(whl.name.split("-")[0])
            hashes.setdefault(name, []).append(hashlib.sha256(whl.read_bytes()).hexdigest())

    lines = [
        "# Hash-pinned build dependencies. Generated by packaging/update_lock.py; don't edit by hand.",
        f"# Top level: {', '.join(TOP_LEVEL)}",
        f"# Resolved with Python {sys.version.split()[0]} on win_amd64.",
        "",
    ]
    for pin in sorted(pins, key=lambda p: _norm(p)):
        name = _norm(pin.split("==")[0])
        marker = MARKERS.get(name)
        line = pin + (f" ; {marker}" if marker else "")
        lines.append(line + " \\")
        digests = sorted(hashes[name])
        for i, digest in enumerate(digests):
            lines.append(f"    --hash=sha256:{digest}" + (" \\" if i < len(digests) - 1 else ""))
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {LOCK}")


if __name__ == "__main__":
    main()
